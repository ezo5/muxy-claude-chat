import json, os, re

root = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(root, "reader.py")) as fh:
    src = fh.read()
with open(os.path.join(root, "..", "server", "claude_chat", "agent_tracker.py")) as fh:
    tracker = fh.read()
# READER_SRC runs as `python3 -c`, so the daemon's agent tracker travels inside it as a module built from its source.
src, n = re.subn(r"^sys\.path\.insert\(0, .*\nimport agent_tracker as tracker\n",
                 lambda m: "tracker = type(sys)(\"agent_tracker\")\nexec(%r, tracker.__dict__)\n" % tracker, src, count=1, flags=re.M)
if n != 1:
    raise SystemExit("agent_tracker import not found in reader.py")
with open(os.path.join(root, "..", "server", "claude_chat", "bootstrap.py")) as fh:
    cli = fh.read()
out = "window.CC = window.CC || {};\nCC.READER_SRC = " + json.dumps(src) + ";\nCC.CLI_SRC = " + json.dumps(cli) + ";\n"
with open(os.path.join(root, "js", "reader-src.js"), "w") as fh:
    fh.write("// generated by build.py from reader.py, server/claude_chat/agent_tracker.py and bootstrap.py\n" + out)
print("js/reader-src.js", len(out))

# The background script has no window and no <script> tags, so it gets the reader as a plain constant.
with open(os.path.join(root, "background.src.js")) as fh:
    bg = fh.read()
with open(os.path.join(root, "background.js"), "w") as fh:
    fh.write("// generated by build.py from background.src.js and bootstrap.py\nconst CLI_SRC = " + json.dumps(cli) + ";\n" + bg)
print("background.js")

dots = os.path.join(root, "icons", "dots")
os.makedirs(dots, exist_ok=True)
for r in range(6):
    for g in range(6):
        for b in range(6):
            with open(os.path.join(dots, "%d%d%d.svg" % (r, g, b)), "w") as fh:
                fh.write('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><circle cx="12" cy="12" r="12" fill="#%02x%02x%02x"/></svg>\n' % (r * 51, g * 51, b * 51))
print("icons/dots", 216)

# muxy fails webview asset requests beyond 32 in flight, so panel.html loads bundles, not 30+ files.
with open(os.path.join(root, "panel.src.html")) as fh:
    page = fh.read()
styles = re.findall(r'<link rel="stylesheet" href="([^"]+)">\n', page)
scripts = [s for s in re.findall(r'<script src="([^"]+)"></script>\n', page) if s != "js/boot.js"]
bundles = {"css/bundle.css": styles, "js/bundle.js": scripts}
for out_path, parts in bundles.items():
    chunks = []
    for part in parts:
        with open(os.path.join(root, part)) as fh:
            chunks.append("/* ---- %s ---- */\n%s\n" % (part, fh.read()))
    sep = ";\n" if out_path.endswith(".js") else "\n"
    with open(os.path.join(root, out_path), "w") as fh:
        fh.write("/* generated by build.py from panel.src.html */\n" + sep.join(chunks))
    print(out_path, len(parts), "files")
page = re.sub(r'(<link rel="stylesheet" href="[^"]+">\n)+', '<link rel="stylesheet" href="css/bundle.css">\n', page)
page = re.sub(r'(<script src="(?!js/boot\.js)[^"]+"></script>\n)+', '<script src="js/bundle.js"></script>\n', page)
with open(os.path.join(root, "panel.html"), "w") as fh:
    fh.write(page.replace("<head>\n", "<head>\n<!-- generated by build.py from panel.src.html -->\n", 1))
print("panel.html")
