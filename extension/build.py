#!/usr/bin/env python3
"""Builds dist/, the folder Muxy loads and the marketplace publishes. Needs nothing but Python.

Each area is js/<area>/_order.txt plus css/<area>.css. A missing area is skipped, so packages add theirs without touching
this file. Bundled into one js and one css file because Muxy fails asset requests beyond 32 in flight.
"""
import hashlib, json, os, shutil, sys

AREAS = ["core-util", "host", "ui", "core", "hub", "chats", "shell", "conversation", "composer", "commands", "rail", "muxy", "review", "sidebar"]
CSS_FIRST = ["tokens", "kit"]
SCRIPT_PRELUDE = ["js/host/probe-core.js", "script-shared.js"]

root = os.path.dirname(os.path.abspath(__file__))
dist = os.path.join(root, "dist")


def read(*parts):
    with open(os.path.join(*parts), encoding="utf-8") as fh:
        return fh.read()


def write(rel, text):
    path = os.path.join(dist, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def area_files(area):
    folder = os.path.join(root, "js", area)
    if not os.path.isdir(folder):
        return []
    order = os.path.join(folder, "_order.txt")
    if not os.path.isfile(order):
        raise SystemExit("js/%s has no _order.txt" % area)
    names = [line.strip() for line in read(order).splitlines() if line.strip() and not line.startswith("#")]
    on_disk = {n for n in os.listdir(folder) if n.endswith(".js")}
    unlisted = on_disk - set(names)
    missing = set(names) - on_disk
    if unlisted or missing:
        raise SystemExit("js/%s/_order.txt: unlisted %s, missing %s" % (area, sorted(unlisted), sorted(missing)))
    return ["js/%s/%s" % (area, n) for n in names]


def chunks(files, open_comment, close_comment):
    return "\n".join("%s ---- %s ---- %s\n%s" % (open_comment, f, close_comment, read(root, f)) for f in files)


# The server package travels in the bundle, readable, and the page installs it. Its version names the folder, so any change is a new folder.
def server_package():
    pkg = os.path.join(root, "..", "server", "claude_chat")
    files = {}
    for folder, dirs, names in os.walk(pkg):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for name in names:
            if name.endswith(".py"):
                rel = os.path.relpath(os.path.join(folder, name), pkg).replace(os.sep, "/")
                files[rel] = read(folder, name)
    h = hashlib.sha256()
    for name in sorted(files):  # same as files_digest in bootstrap.py
        h.update(name.encode() + b"\0" + files[name].encode() + b"\0")
    base = json.loads(read(root, "package.json"))["version"]
    return {"version": "%s-%s" % (base, h.hexdigest()[:12]), "files": files}


def build(with_sample=True):
    shutil.rmtree(dist, ignore_errors=True)
    os.makedirs(dist)

    bootstrap = read(root, "..", "server", "claude_chat", "bootstrap.py")
    head = "// generated by build.py\nwindow.CC = window.CC || {};\nCC.BOOTSTRAP_SRC = %s;\nCC.SERVER_PACKAGE = %s;\n" % (json.dumps(bootstrap), json.dumps(server_package()))
    files = [f for area in AREAS for f in area_files(area)] + ["js/boot.js"]
    write("js/bundle.js", head + chunks(files, "//", ""))
    write("js/guard.js", read(root, "js", "guard.js"))

    css_names = CSS_FIRST + AREAS
    css_files = ["css/%s.css" % c for c in css_names if os.path.isfile(os.path.join(root, "css", c + ".css"))]
    write("css/bundle.css", "/* generated by build.py */\n" + chunks(css_files, "/*", "*/"))

    if with_sample:
        write("js/dev-sample.js", "// generated by build.py\n" + chunks(area_files("dev-sample"), "//", ""))
        write("css/dev-sample.css", read(root, "css", "dev-sample.css"))

    write("index.html", read(root, "index.src.html"))
    # 2.x's tabs come back as tab type `chat`, whose page says where their chat went.
    write("moved.html", read(root, "moved.src.html"))
    write("js/moved.js", read(root, "moved.js"))
    # A script runs without a page, so what it shares with the page travels with it.
    prelude = "\n".join(read(root, f) for f in SCRIPT_PRELUDE)
    for name in sorted(os.listdir(os.path.join(root, "scripts"))):
        write("scripts/" + name, prelude + "\n" + read(root, "scripts", name))
    shutil.copytree(os.path.join(root, "assets"), os.path.join(dist, "assets"))
    shutil.copy(os.path.join(root, "package.json"), os.path.join(dist, "package.json"))
    print("dist/: %d js files, %d css files%s" % (len(files), len(css_files), "" if with_sample else ", no sample"))


if __name__ == "__main__":
    build(with_sample="--no-sample" not in sys.argv)
