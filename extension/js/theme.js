window.CC = window.CC || {};

CC.theme = (function () {
  const handlers = [];
  const probe = document.createElement("span");
  const ctx = document.createElement("canvas").getContext("2d", { willReadFrequently: true });

  function apply(theme) {
    document.documentElement.dataset.scheme = theme != null && theme.colorScheme === "light" ? "light" : "dark";
  }

  // [r, g, b, a] of a CSS token; the canvas also parses color-mix results serialized as color(srgb …).
  function rgba(token) {
    probe.style.color = "var(--" + token + ")";
    document.body.appendChild(probe);
    ctx.clearRect(0, 0, 1, 1);
    ctx.fillStyle = getComputedStyle(probe).color;
    probe.remove();
    ctx.fillRect(0, 0, 1, 1);
    const d = ctx.getImageData(0, 0, 1, 1).data;
    return [d[0], d[1], d[2], d[3] / 255];
  }

  // muxy.tabs.setIcon only loads SVG files from the extension folder, so the dot is the nearest of the
  // 6×6×6 colors pre-generated by build.py in icons/dots/.
  function dotIcon(token) {
    const c = rgba(token);
    const bg = rgba("bg");
    return "icons/dots/" + [0, 1, 2].map(function (i) {
      return Math.round((c[i] * c[3] + bg[i] * (1 - c[3])) / 51);
    }).join("") + ".svg";
  }

  apply(muxy.theme);
  if (typeof muxy.onThemeChange === "function") {
    muxy.onThemeChange(function (theme) {
      apply(theme);
      handlers.forEach(function (fn) {
        fn();
      });
    });
  }

  return {
    dotIcon: dotIcon,
    onChange: function (fn) {
      handlers.push(fn);
    },
  };
})();
